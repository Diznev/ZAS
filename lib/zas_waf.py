def detect_waf(response_text, response_headers, cookies=None, status_code=None):
    """Detect WAF from HTTP response.
    
    Args:
        response_text: HTML body
        response_headers: dict of response headers
        cookies: dict of cookies (optional)
        status_code: HTTP status code (optional)
    
    Returns:
        dict with keys: waf, confidence, details, blocked
    """
    result = {
        "waf": None,
        "confidence": 0,
        "details": {},
        "blocked": False,
        "all_detected": [],
    }
    
    headers_str = "\n".join(f"{k}: {v}" for k, v in response_headers.items()).lower()
    body_lower = response_text.lower() if response_text else ""
    cookies_str = " ".join(cookies.keys()).lower() if cookies else ""
    
    # Check if blocked (403/406/429 status codes)
    if status_code in (403, 406, 429):
        result["blocked"] = True
    
    detected = []
    
    for waf_name, sigs in WAF_SIGNATURES.items():
        score = 0
        matched = []
        
        # Check headers
        for header_pattern, value_patterns in sigs["headers"].items():
            if "*" in header_pattern:
                # Wildcard header name (e.g., x-amzn-*)
                prefix = header_pattern.replace("*", "")
                for h_name, h_val in response_headers.items():
                    if h_name.lower().startswith(prefix.lower()):
                        score += 30
                        matched.append(f"header:{h_name}")
                        break
            else:
                # Exact header name
                for h_name, h_val in response_headers.items():
                    if h_name.lower() == header_pattern.lower():
                        for vp in value_patterns:
                            if re.search(vp.lower(), str(h_val).lower()):
                                score += 30
                                matched.append(f"header:{h_name}")
                                break
        
        # Check cookies
        for pattern in sigs["cookies"]:
            if "*" in pattern:
                prefix = pattern.replace("*", "")
                if any(c.startswith(prefix) for c in cookies_str.split()):
                    score += 20
                    matched.append(f"cookie:{pattern}")
            else:
                if pattern.lower() in cookies_str:
                    score += 20
                    matched.append(f"cookie:{pattern}")
        
        # Check block patterns
        for pattern in sigs["block_patterns"]:
            if re.search(pattern.lower(), body_lower):
                score += 25
                matched.append(f"block:{pattern}")
        
        if score > 0:
            detected.append({
                "waf": waf_name,
                "score": score,
                "matched": matched,
                "confidence": min(100, int(score * sigs["confidence"] / 100)),
            })
    
    if detected:
        # Sort by score
        detected.sort(key=lambda x: x["score"], reverse=True)
        best = detected[0]
        
        result["waf"] = best["waf"]
        result["confidence"] = best["confidence"]
        result["details"] = best
        result["all_detected"] = [d["waf"] for d in detected]
    
    return result


